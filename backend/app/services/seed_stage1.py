def get_or_create_role(db: Session, role_code: str, role_name: str, description: str) -> Role:
    role = db.scalar(select(Role).where(Role.role_code == role_code))
    if role is None:
        role = Role(role_code=role_code, role_name=role_name, description=description, is_system_role=True)
        db.add(role)
        db.flush()
    return role


